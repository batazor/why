import { defineCollection, z } from 'astro:content';
import { glob } from 'astro/loaders';

/**
 * Урок = нарратив (переводится) + колода шагов кода (НЕ переводится).
 *
 * Код намеренно лежит вне этого файла, в src/code/<slug>.ts, один на все локали.
 * Если положить код в переводимый файл, версии разъезжаются: правишь пример в en,
 * забываешь в ru, и получаешь баг, который воспроизводится только на одном языке.
 * Шаги связываются по `id`, консистентность проверяет `npm run check:steps`.
 */
const lessons = defineCollection({
  loader: glob({ pattern: '**/*.mdx', base: './src/content/lessons' }),
  schema: z.object({
    title: z.string(),
    description: z.string(),
    /** Боль, ради которой урок существует. Выводится в карточке каталога. */
    problem: z.string(),
    /**
     * Реальные случаи, где эта же ошибка уже стоила денег: короткий пересказ и
     * ссылка на источник. Без них урок читается как выдуманная задача, а он не
     * выдуманный.
     *
     * Пересказ — проза, поэтому переводится. Ссылка одна и та же во всех
     * локалях: совпадение набора и порядка проверяет check:steps.
     */
    incidents: z
      .array(
        z.object({
          title: z.string(),
          text: z.string(),
          url: z.string().url(),
        }),
      )
      .default([]),
    /**
     * Задание в том виде, в каком его принесли: постановка от заказчика.
     *
     * Есть не у всякого урока. Разбор паттерна начинается с боли («Проблема»),
     * а разбор задачи — с чужого текста, который надо выполнить; на странице
     * задание встаёт на место проблемы, потому что для такого урока это одно и
     * то же место, и два блока подряд об одном читателю мешают.
     *
     * `problem` при этом остаётся: он живёт в карточке каталога, где задания
     * нет и где нужно одной фразой сказать, ради чего урок.
     */
    brief: z
      .object({
        /** Подпись карточки: «Задание», «Письмо от продукта». */
        label: z.string(),
        /** Кто это сказал. */
        source: z.string().optional(),
        text: z.string(),
      })
      .optional(),
    tags: z.array(z.string()).default([]),
    /** Порядок в каталоге; одинаковый во всех локалях. */
    order: z.number().default(100),
    draft: z.boolean().default(false),
    /** Ключ колоды кода в src/code/. По умолчанию равен slug урока. */
    deck: z.string().optional(),
    /**
     * Серия: ключ книги, главами которой урок является.
     *
     * Один разбор длиной в тридцать шагов не читается, поэтому он разбит на
     * главы — отдельные уроки с общим ключом. По нему страница собирает
     * оглавление и соседей: внутри серии соседи считаются по `order` и
     * черновики не отбрасываются, иначе оглавление недописанной книги пустое.
     */
    series: z.string().optional(),
    /**
     * Тексты комментариев к коду. Код общий для всех локалей, поэтому
     * комментарии в нём стоят placeholder'ами `{{ключ}}`, а сами тексты живут
     * здесь — как и всё остальное, что является прозой.
     *
     * Набор ключей обязан совпадать между локалями; это проверяет check:steps.
     */
    comments: z.record(z.string(), z.string()).default({}),
    /**
     * Глоссарий урока: термин → определение. В тексте слово помечается
     * `<span data-term="ключ">`, определение подставляется на клиенте.
     *
     * Ключ отделён от написания намеренно: в тексте слово склоняется («маржу
     * по SKU»), а определение у него одно на все упоминания и все падежи.
     */
    terms: z.record(z.string(), z.string()).default({}),
    /**
     * Подписи на схеме. Схема, как и колода кода, общая для всех локалей,
     * поэтому проза в ней стоит placeholder'ами `{{ключ}}`, а тексты живут
     * здесь. Идентификаторы из кода (`POST /charge`, `Closed`, `idempotency_keys`)
     * placeholder'ами не оборачиваются: они одинаковы на всех языках.
     */
    labels: z.record(z.string(), z.string()).default({}),
    steps: z
      .array(
        z.object({
          /** Должен совпадать с id шага в колоде кода. */
          id: z.string(),
          title: z.string(),
          narration: z.string(),
          /**
           * Текст пометки поверх схемы. Нужен ровно тогда, когда в спеке схемы
           * для этого шага объявлена annotation — связь проверяет check:steps.
           */
          note: z.string().optional(),
          /**
           * Что появляется на схеме на этом шаге: карточкой под текстом.
           *
           * В абзаце новый сервис растворяется — «потом данные уезжают в
           * хранилище» читается как подробность, а не как новая коробка на
           * схеме. Карточка делает появление видимым.
           *
           * `element` — id из модели LikeC4, одинаковый во всех локалях: имя и
           * технологию карточка берёт из модели, чтобы подпись не разошлась со
           * схемой. `role` — проза, одна фраза о том, зачем элемент нужен.
           */
          added: z
            .array(z.object({ element: z.string(), role: z.string() }))
            .optional(),
          /**
           * Подписи для перетаскивания: текст карточки в нарративе и подсказка
           * в пустом слоте схемы. Нужны, когда схема объявляет `drop` на этом
           * шаге; связь проверяет check:steps.
           */
          drag: z
            .object({
              chip: z.string(),
              slot: z.string(),
              action: z.string().optional(),
              applied: z.string().optional(),
              result: z.string().optional(),
            })
            .optional(),
        }),
      )
      .min(1),
    quiz: z
      .array(
        z.object({
          question: z.string(),
          options: z.array(z.string()).min(2),
          /** Индекс правильного варианта в `options`. */
          answer: z.number().int().nonnegative(),
          explanation: z.string(),
        }),
      )
      .default([]),
  }),
});

/**
 * Документы сервиса, которые урок показывает в редакторе: словарь, README, ADR.
 *
 * Это проза, а значит переводится — поэтому файл на локаль, а не общий ассет
 * рядом с колодой кода. И это markdown, который читателю показывают
 * отрендеренным: словарь, набранный как исходник, читается хуже той таблицы,
 * ради которой он написан.
 *
 * Путь внутри локали повторяет путь в дереве урока: `<локаль>/<урок>/<путь>`.
 * По нему `FileEditor` и находит содержимое файла.
 */
const docs = defineCollection({
  loader: glob({
    pattern: '**/*.md',
    base: './src/content/docs',
    /**
     * Id — путь как он есть, без слагификации: по умолчанию `GLOSSARY.md`
     * превращается в `glossary`, и файл дерева по своему имени уже не находится.
     * А имя файла здесь — часть содержания урока, его нельзя терять.
     */
    generateId: ({ entry }) => entry.replace(/\.md$/, ''),
  }),
});

export const collections = { lessons, docs };
