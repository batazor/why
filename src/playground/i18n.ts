const dictionaries: Record<string, Record<string, string>> = { en, ru };

export type T = (key: string, params?: Record<string, string>) => string;

export function translator(lang: string): T {
  const dict = dictionaries[lang] ?? en;
  return (key, params) => {
    let text = dict[key] ?? (en as Record<string, string>)[key] ?? key;
    for (const [name, value] of Object.entries(params ?? {})) text = text.replaceAll(`{${name}}`, value);
    return text;
  };
}
