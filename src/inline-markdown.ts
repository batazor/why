/**
 * Инлайн-разметка для прозы, которая живёт во frontmatter урока.
 *
 * Полный markdown здесь не нужен и мешал бы: нарратив — это несколько
 * предложений, а не документ, и списки с заголовками в нём взяться неоткуда.
 * Поддержаны ровно те три вещи, что в текстах уроков встречаются.
 *
 * HTML экранируется ДО разметки. Тексты пишутся как обычная проза, и случайная
 * угловая скобка не должна превращаться в тег — а вставленные потом <code> и
 * <strong> уже наши и экранированию не подлежат.
 */
const ESCAPE: Record<string, string> = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
};

export function inlineMarkdown(text: string): string {
  return (
    text
      .replace(/[&<>"]/g, (char) => ESCAPE[char])
      // Код первым: внутри него звёздочки — это звёздочки, а не разметка.
      .replace(/`([^`]+)`/g, '<code>$1</code>')
      .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
      // Курсив только после двойных звёздочек, иначе `**жирный**` съелся бы
      // как курсив с лишней звёздочкой по краям.
      .replace(/(^|[\s(«—-])\*([^*\n]+)\*/g, '$1<em>$2</em>')
  );
}
