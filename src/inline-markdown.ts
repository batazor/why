/**
 * Инлайн-разметка для прозы, которая живёт во frontmatter урока.
 *
 * Полный markdown здесь не нужен и мешал бы: нарратив — это несколько
 * предложений, а не документ, и списки с заголовками в нём взяться неоткуда.
 * Поддержаны ровно те вещи, что в текстах уроков встречаются: код, жирный,
 * курсив и термин глоссария.
 *
 * HTML экранируется ДО разметки. Тексты пишутся как обычная проза, и случайная
 * угловая скобка не должна превращаться в тег — а вставленные потом <code> и
 * <strong> уже наши и экранированию не подлежат.
 */
const ESCAPE: Record<string, string> = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
};

/**
 * Термин глоссария: `[[ключ]]` или `[[ключ|как написано в тексте]]`.
 *
 * Ключ отделён от написания по той же причине, что и в глоссарии урока: в
 * тексте слово склоняется («агрегату»), а определение у него одно на все
 * упоминания. Определение подставляет клиентский скрипт страницы урока по
 * `data-term`; слово без определения остаётся обычным текстом.
 */
const TERM = /\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/g;

/**
 * Ссылка: `[текст](адрес)`.
 *
 * Адрес пишется относительным — `../why-cqrs/`, — и это не стиль, а
 * требование: сайт живёт и в корне домена, и на подпути (`/why` у Pages), а
 * абсолютный путь на подпути уводит в 404. Относительный считается от адреса
 * страницы, и у уроков он всегда со слешем на конце.
 */
const LINK = /\[([^\]\n]+)\]\(([^)\s]+)\)/g;

export function inlineMarkdown(text: string): string {
  return (
    text
      .replace(/[&<>"]/g, (char) => ESCAPE[char])
      // Термины до остальной разметки: внутри них может стоять `код`, и
      // подставленный span не должен попасть под замену кавычек.
      .replace(TERM, (_, key: string, label?: string) =>
        `<span data-term="${key}">${label ?? key}</span>`,
      )
      // Ссылки после терминов: в подписи ссылки может стоять термин, а вот
      // ключ термина ссылкой быть не может.
      .replace(LINK, (_, text: string, href: string) => `<a href="${href}">${text}</a>`)
      // Код первым: внутри него звёздочки — это звёздочки, а не разметка.
      .replace(/`([^`]+)`/g, '<code>$1</code>')
      .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
      // Курсив только после двойных звёздочек, иначе `**жирный**` съелся бы
      // как курсив с лишней звёздочкой по краям.
      .replace(/(^|[\s(«—-])\*([^*\n]+)\*/g, '$1<em>$2</em>')
  );
}
