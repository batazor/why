/**
 * Привязка шагов урока к view'ам LikeC4.
 *
 * `FlowSpec` рисуется руками: координаты, рёбра, пометки. Это верно, пока
 * картинка — иллюстрация к коду. Но урок про границы показывает не поток, а
 * вложенность: контексты → слайсы → слои внутри слайса. Раскладку такой
 * картинки считает LikeC4 из модели в `likec4/`, и рисовать её руками значило
 * бы держать вторую, расходящуюся копию той же архитектуры.
 *
 * Поэтому колода может вести разбор не `FlowSpec`, а этим: шаг → id view.
 * Существование view проверяет scripts/check-steps.mjs: опечатка в id иначе
 * доезжает до читателя пустым полотном.
 */
export type LikeC4Spec = {
  /** Высота полотна в пикселях. */
  height: number;
  /**
   * Своя высота у отдельных шагов.
   *
   * Общая высота подобрана под кадры рядом с текстом. Итоговому кадру во всю
   * ширину её мало: схема целиком упирается в неё раньше, чем в ширину окна, и
   * сжимается до мелких подписей, хотя по ширине места хватило бы.
   */
  heights?: Record<string, number>;
  /**
   * Стикер-пометка поверх кадра: шаг → элемент модели, к которому он привязан.
   *
   * Координат у LikeC4 нет — раскладку считает Graphviz, — поэтому стикер
   * привязан не к точке, а к элементу: кадр находит его коробку на экране и
   * ставит стикер с той стороны, что указана. Кадр можно зумить и двигать, и
   * стикер едет вместе с элементом.
   *
   * Текст — проза, живёт в `steps[].note` урока, как у стикеров на схемах React
   * Flow. Связь «пометка ↔ текст» и существование элемента проверяет
   * scripts/check-steps.mjs.
   *
   * Стикер ставят не на каждый кадр, а туда, где он нужен: он указывает на
   * деталь схемы, которую легко пропустить или понять неправильно, называет
   * её по имени — без «он» и «это» — и не повторяет ни карточку «новое на
   * схеме», ни текст шага. Утверждению, которому на схеме не на что
   * указать, место в тексте.
   */
  notes?: Record<string, LikeC4Note>;
  /**
   * Рамки групп поверх последовательности: шаг → группы шагов.
   *
   * Фрагменты LikeC4 — слова UML (`opt`, `loop`, `par`, `try`), и транзакцию
   * ими не назвать, не соврав. Рамка своя: вокруг шагов с `from` по `to`
   * включительно, с подписью из `labels` урока — на языке страницы.
   */
  groups?: Record<string, LikeC4Group[]>;
  /**
   * Шаги, на которых у линий нет подписей: только связи.
   *
   * Итоговая схема показывает структуру, а подписи — «create job», «status,
   * list» — это уже порядок запросов, у которого свои кадры. Подпись висит на
   * связи в модели, и убрать её одному кадру средствами LikeC4 нельзя:
   * пустой `title` в view он не принимает. Поэтому подписи прячет кадр.
   */
  bare?: string[];
  /**
   * Шаг разбора → id view из `likec4/views.c4`.
   *
   * Шага может не быть в карте: тогда на полотне остаётся предыдущая картинка.
   * Это нужно там, где два шага говорят об одном уровне вложенности — схема
   * стоит на месте, меняются только код и текст рядом.
   */
  views: Record<string, string>;
  /**
   * Шаги, на которых у карточек показаны теги.
   *
   * Тег — это лейбл вида контекста (core, supporting, generic). Он висит на
   * элементе модели, то есть виден в любом view, где элемент есть; а урок
   * говорит про виды на своём шаге, и до него различие на схеме появляться не
   * должно. Поэтому теги включает шаг, а не модель.
   */
  tags?: string[];
  /**
   * Шаги, у которых кадр идёт во всю ширину окна: текст сверху, кадр под ним.
   *
   * По умолчанию кадр стоит рядом с текстом, в колонке шириной в половину
   * разбора. Этот список — исключение для больших кадров: в половине ширины
   * подписи в них не прочитать, а текста рядом такому кадру почти не нужно.
   *
   * Колонка текста при этом не меняется — её ширина задана треком сетки, — так
   * что переносов в абзацах не случается; шаги просто сдвигаются вниз.
   */
  wide?: string[];
};

export type LikeC4Note = {
  /** Полный id элемента модели: `scraper.results`. */
  element: string;
  /** С какой стороны элемента стоит стикер; стрелка смотрит на элемент. */
  side: 'top' | 'right' | 'bottom' | 'left';
  /** Ширина стикера в пикселях; по умолчанию 200. */
  width?: number;
};

export type LikeC4Group = {
  /** Номер первого шага последовательности, с единицы. */
  from: number;
  /** Номер последнего шага, включительно. */
  to: number;
  /** Ключ подписи в `labels` урока. */
  label: string;
};
