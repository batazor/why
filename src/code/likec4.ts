/**
 * Привязка шагов урока к view'ам LikeC4.
 *
 * `FlowSpec` рисуется руками: координаты, рёбра, пометки. Это верно, пока
 * картинка — иллюстрация к коду. Но урок про границы показывает не поток, а
 * вложенность: контексты → слайсы → слои внутри слайса. Раскладку такой
 * картинки считает LikeC4 из модели в `likec4/`, и рисовать её руками значило
 * бы держать вторую, расходящуюся копию той же архитектуры.
 *
 * Поэтому колода может вести разбор не `FlowSpec`, а этим: шаг → id view.
 * Существование view проверяет scripts/check-steps.mjs: опечатка в id иначе
 * доезжает до читателя пустым полотном.
 */
export type LikeC4Spec = {
  /** Высота полотна в пикселях. */
  height: number;
  /**
   * Шаг разбора → id view из `likec4/views.c4`.
   *
   * Шага может не быть в карте: тогда на полотне остаётся предыдущая картинка.
   * Это нужно там, где два шага говорят об одном уровне вложенности — схема
   * стоит на месте, меняются только код и текст рядом.
   */
  views: Record<string, string>;
};
