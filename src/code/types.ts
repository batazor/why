/**
 * Один шаг колоды: то, что видно в правой панели. Общее для всех локалей,
 * поэтому всё содержимое — английское и без объясняющих комментариев.
 */
export type CodeStep = {
  id: string;
  /** Подпись панели — имя файла или команда. Не переводится. */
  caption?: string;
  /** Код может отсутствовать: шаг бывает чисто диаграммным или концептуальным. */
  lang?: string;
  code?: string;
  /** Вывод/лог под кодом. Предзаписанный: рантайм в браузере не нужен. */
  output?: string;
  /** Подсветить вывод как ошибку. */
  outputTone?: 'ok' | 'bad';
  /**
   * Что открывать в песочнице Lean. По умолчанию — файл, собранный из всех
   * шагов по этот включительно: фрагмент сам по себе не соберётся.
   *
   * `{ find, replace }` — шаг показывает правку существующего кода, а не новый
   * код. В песочницу уходит собранный файл с применённой правкой: открывать
   * голый фрагмент бессмысленно, читателю нужен файл, который он может починить.
   */
  playground?: { find: string; replace: string }[];
  /**
   * Шаг показывает тот же блок, что и предыдущий, с другой подсвеченной
   * строкой. Два следствия: в собранный файл он не дописывается (иначе блок
   * попал бы туда дважды) и в разборе он делит с предыдущим одну панель,
   * которая при переходе остаётся на месте.
   */
  repeatsPrevious?: boolean;
};

export type CodeDeck = CodeStep[];

/**
 * Колода может дополнительно экспортировать `diagram` — имя файла в src/code/.
 * Это одна SVG на весь разбор: элементы помечаются data-show="<id шага> ...",
 * плеер зажигает нужные. Именно поэтому схема одна, а не по одной на шаг —
 * так переходы между состояниями анимируются, а не мигают.
 *
 *     export const diagram = 'circuit-breaker.svg';
 *
 * Хранится строкой, а не импортом `?raw`: колоду читает ещё и
 * scripts/check-steps.mjs через обычный node-импорт, который `?raw` не умеет.
 */
export type DeckDiagram = string;
