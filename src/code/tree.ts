/**
 * Дерево файлов сервиса, которое урок заполняет по шагам.
 *
 * Панель кода показывает один файл — этого хватает, пока урок про алгоритм.
 * Но урок про раскладку сервиса обязан показывать каталог: где файл лежит и
 * рядом с чем он появился. Поэтому правая половина разбора — не панель, а
 * редактор: дерево, содержимое, и с каждым шагом в дереве новые файлы.
 *
 * Как колода кода и схема, дерево общее для всех локалей: в нём только
 * английский. Вся проза — в нарративе локализованного урока.
 */
export type TreeFile = {
  /** Путь от корня сервиса: `internal/user/domain/user.go`. */
  path: string;
  /**
   * Шаг, на котором файл появляется в дереве. У файла, который был заведён
   * раньше (`seed`), шага появления нет — он виден с самого начала.
   */
  from?: string;
  /**
   * Файл достался разбору по наследству: его завели в предыдущей части, и
   * здесь он просто есть. Такой файл виден с первого шага и новым не
   * помечается — «новое» относится к этой части, а не к истории проекта.
   */
  seed?: boolean;
  /** Язык для подсветки. Без него файл показывается как текст. */
  lang?: string;
  /**
   * Код файла — общий для всех локалей, поэтому только английский.
   *
   * Может отсутствовать: тогда это документ, а не код, и содержимое берётся из
   * коллекции `docs` по пути `<локаль>/<урок>/<path>`. Документ — проза, значит
   * переводится, и показывается отрендеренным: словарь, набранный как исходник,
   * читается хуже таблицы, ради которой он написан.
   */
  code?: string;
  /**
   * Правки файла на следующих шагах: тот же путь, другое содержимое.
   *
   * Урок показывает код в развитии — сперва как пишут обычно, потом как
   * получается, когда правило переехало в тип. Заводить под это второй файл
   * значило бы соврать про раскладку: в репозитории файл один, и он меняется.
   */
  edits?: { from: string; code: string }[];
};

/**
 * Что редактор показывает на шаге.
 *
 * Делить панель пополам всегда — значит всегда показывать половину ненужного:
 * на шаге, где файл только появился, читать в нём нечего, а на шаге про
 * содержимое дерево уже рассказало всё, что могло, и отнимает у кода ширину,
 * которой и так мало.
 */
export type EditorView = 'tree' | 'file' | 'both';

export type FileTreeStep = {
  /**
   * Какой файл открыт. Шаг может не называть файл: тогда остаётся открытым
   * тот, что был, — читатель сам его выбрал и терять выбор не просил.
   */
  open?: string;
  /** По умолчанию `both`. */
  view?: EditorView;
  /**
   * Шагу нужен свой редактор, а не общий с соседями.
   *
   * Подряд идущие шаги делят один экземпляр: дерево растёт, файл меняется, а
   * панель стоит на месте. Итоговому шагу это во вред — он показывает дерево и
   * файл сразу, и в общей панели этот режим виден рядом с соседним шагом,
   * который просил только файл.
   */
  standalone?: boolean;
  /**
   * Строки открытого файла, о которых говорит шаг: 1 — первая строка.
   *
   * Подсветка объявлена в шаге, а не маркером в коде: один и тот же файл
   * разбирают несколько шагов, и маркеры пришлось бы держать копией файла на
   * каждый из них — то есть соврать про то, что файл один.
   */
  lines?: number[];
  /**
   * Шаг подводит итог главы: в дереве помечено всё, что глава добавила или
   * изменила, а не только то, что случилось на этом шаге.
   *
   * На остальных шагах пометка — про шаг: появившаяся строка одна, и её видно.
   * Итоговый шаг говорит о главе целиком, и читателю нужен другой ответ — что
   * из десятка файлов трогали здесь, а что досталось по наследству.
   */
  summary?: boolean;
  /**
   * Редактор идёт во всю ширину окна, а текст шага стоит над ним.
   *
   * Нужно итоговому шагу: он показывает дерево и файл сразу, и в половине
   * ширины из этого не читается ни то, ни другое.
   */
  wide?: boolean;
};

/**
 * Каталог, который появился раньше своего содержимого.
 *
 * Обычный каталог объявлять не нужно: он появляется вместе с первым своим
 * файлом, и номер шага у него — минимум по содержимому. Но раскладку иногда
 * объясняют до кода: сперва видно, из каких частей состоит домен, и только
 * потом — что внутри части. Пустой каталог в дереве и есть эта часть.
 */
export type TreeDir = {
  /** Путь от корня сервиса: `invoice/issuing`. */
  path: string;
  /** Шаг, на котором каталог появляется в дереве. */
  from?: string;
  /** Каталог из предыдущей части: виден сразу и новым не помечается. */
  seed?: boolean;
};

export type FileTreeSpec = {
  /**
   * Имя корневого каталога. Показывается верхней строкой дерева, чтобы было
   * видно, что путь отсчитывается от сервиса, а не от репозитория.
   */
  root: string;
  steps: Record<string, FileTreeStep>;
  files: TreeFile[];
  /** Каталоги, которые появляются сами по себе, без файлов внутри. */
  dirs?: TreeDir[];
};

/** Каким глава оставила файл: код после последней правки. */
export const finalCode = (file: TreeFile): string | undefined =>
  file.edits?.length ? file.edits[file.edits.length - 1].code : file.code;

/** Код без строк-аннотаций `// {{key}}`: то, что в файле на самом деле написано. */
const withoutNotes = (code: string): string =>
  code
    .split('\n')
    .filter((line) => !/^\s*\/\/ \{\{\w+\}\}\s*$/.test(line))
    .join('\n');

/**
 * Наследство главы: дерево, каким его оставила предыдущая.
 *
 * Серия ведёт один сервис, и глава обязана начинать с того, чем закончилась
 * прошлая. Копия файлов в каждой колоде это правило не держит: стоит поправить
 * файл в одной главе, и следующая показывает уже другой сервис. Поэтому
 * наследство не переписывают, а берут у предыдущей колоды.
 *
 * `edits` — правки унаследованных файлов в этой главе, по пути.
 *
 * `notes` — тот же файл с другими аннотациями: глава вправе подписать в старом
 * коде то, о чём говорит она. Менять при этом сам код нельзя — за этим следит
 * проверка ниже.
 */
export function inherit(
  prev: FileTreeSpec,
  edits: Record<string, NonNullable<TreeFile['edits']>> = {},
  notes: Record<string, string> = {},
): TreeFile[] {
  const known = new Set(prev.files.map((file) => file.path));
  for (const path of [...Object.keys(edits), ...Object.keys(notes)]) {
    if (!known.has(path)) throw new Error(`inherit: в наследстве нет файла ${path}`);
  }

  return prev.files.map((file) => {
    const left = finalCode(file);
    const noted = notes[file.path];
    if (noted !== undefined && withoutNotes(noted) !== withoutNotes(left ?? '')) {
      throw new Error(`inherit: ${file.path} — аннотации меняют код, а не подписи`);
    }

    return {
      path: file.path,
      seed: true,
      lang: file.lang,
      code: noted ?? left,
      edits: edits[file.path],
    };
  });
}
